import assert from 'node:assert/strict';
import {newSong,newWorship} from '../lib/types.ts';
import {librarySongs,importLibrarySongs,librarySongKey} from '../lib/song-library.ts';
const a={...newSong(),title:'은혜',key:'D',fixedId:'fixed-old',pages:[{id:'original-page',width:1200,height:1800,layout:{x:.1,y:.2,width:.7,size:.04,margin:false}}],form:[{id:'form-original',type:'Cx2'}],markers:[{id:'marker-original',pageId:'original-page',type:'V1',x:.1,y:.3,size:.04}],exports:['old-export'],link:'https://youtu.be/example',notes:'공통 합주 메모',parts:{드럼:'조용하게'}};
const b={...newSong(),title:'은혜',key:'G'};
const make=(id,date,songs,extra={})=>({id,date,title:'주일예배',data:{...newWorship(),date,songs},published:true,version:3,revision:2,finalized:true,updated:0,changes:[],seen:0,...extra});
const old=make('past-a','2026-09-20',[a,b]);
const changed=make('past-b','2026-09-27',[a],{hasDraft:true,draft:{...newWorship(),date:'2026-09-28',songs:[{...a,title:'은혜 수정 초안'}]}});
const draft=make('draft','2026-09-29',[b],{published:false});
const entries=librarySongs([old,changed,draft,make('current','2026-10-04',[a]),make('trash','2026-10-01',[a],{deleted:true})],'current');
assert.equal(entries.length,5);
assert.ok(entries.every(e=>!['current','trash'].includes(e.serviceId)));
assert.equal(entries.filter(e=>e.kind==='draft').length,2);
assert.equal(entries.find(e=>e.serviceId==='past-b'&&e.kind==='complete').song.title,'은혜');
assert.equal(entries.find(e=>e.serviceId==='past-b'&&e.kind==='draft').song.title,'은혜 수정 초안');
assert.equal(new Set(entries.map(e=>e.id)).size,5,'Separate dates, keys and snapshot kinds remain individually selectable');
const first=entries.find(e=>e.serviceId==='past-a'&&e.song.key==='D');
const second=entries.find(e=>e.serviceId==='past-a'&&e.song.key==='G');
const before=JSON.stringify(old),copies=importLibrarySongs([], [second,first,first]);
assert.deepEqual(copies.map(s=>s.key),['G','D'],'Selection order is preserved and duplicates ignored');
const copy=copies[1];
assert.notEqual(copy.id,a.id);assert.notEqual(copy.form[0].id,a.form[0].id);assert.notEqual(copy.markers[0].id,a.markers[0].id);
assert.equal(copy.pages[0].id,a.pages[0].id);assert.equal(copy.markers[0].pageId,copy.pages[0].id);
assert.deepEqual(copy.pages,a.pages);assert.deepEqual(copy.layout,a.layout);assert.equal(copy.link,a.link);assert.deepEqual(copy.parts,a.parts);assert.equal(copy.notes,a.notes);
assert.equal(copy.fixedId,undefined,'Importing library material must not offer to overwrite a fixed original');
assert.deepEqual(copy.exports,[],'Exports must be regenerated for the new service');
assert.equal(librarySongKey(copy.librarySource),first.id);
copy.pages[0].layout.x=.8;copy.markers[0].y=.9;copy.parts.드럼='수정';copy.form[0].type='Bridge x 2';
assert.equal(JSON.stringify(old),before,'Imported edits cannot mutate the original service');
assert.deepEqual(importLibrarySongs(copies,[first,second]),[],'Reopening does not duplicate prior imports');
assert.equal(importLibrarySongs([copies[0]],[first]).length,1,'Removing a song permits reimport');
assert.throws(()=>importLibrarySongs(Array.from({length:29},newSong),[first,second]),/30곡/);
assert.equal(importLibrarySongs(Array.from({length:29},newSong),[first]).length,1);
console.log('PASS: individual complete/draft songs, current/trash exclusion, selection order, exact-source deduplication, independent copies, original files and annotations, source provenance and 30-song boundary');
