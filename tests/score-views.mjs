import assert from 'node:assert/strict';
import {notesForSong,notesForPage,scoreViewLabel} from '../lib/score-views.ts';
const note=(id,pageId,text)=>({id,pageId,text,x:.2,y:.3,size:.025,color:'#315d48'});
const song={id:'song',pages:[{id:'page-1'},{id:'page-2'}]};
const make=(id,position,notes)=>({serviceId:'week',version:2,userId:id,name:id,position,own:id==='me',members:[],songs:{song:{notes,basedVersion:1,revision:3,updated:1}}});
const drum=make('me','드럼',[note('d1','page-1','쉼'),note('d2','page-2','필인'),note('missing','replaced-page','기억할 메모')]);
const vocal=make('vocal','싱어',[note('v1','page-1','하모니')]);
assert.deepEqual(notesForPage(drum,song,'page-1').map(n=>n.id),['d1']);
assert.deepEqual(notesForPage(drum,song,'page-2').map(n=>n.id),['d2']);
assert.deepEqual(notesForPage(vocal,song,'page-1').map(n=>n.id),['v1']);
assert.deepEqual(notesForPage(drum,{...song,id:'another-song'},'page-1'),[],'A reused raw page never brings another song’s notes');
assert.deepEqual(notesForSong(drum,song).missing.map(n=>n.text),['기억할 메모']);
assert.equal(notesForSong(drum,song).needsReview,true);
assert.equal(notesForSong({...drum,version:1},song).needsReview,false);
assert.deepEqual(notesForPage({...drum,userId:null,songs:{}},song,'page-1'),[]);
assert.equal(notesForSong(make('me','드럼',[]),song).needsReview,false,'Explicitly cleared notes do not need review');
assert.equal(scoreViewLabel(drum),'내 악보 · 드럼 · me');
assert.equal(scoreViewLabel(vocal),'보컬 · vocal');
assert.equal(scoreViewLabel({...drum,userId:null}),'공통 송폼 악보');
console.log('PASS: separate authors, songs and pages; replaced-page recovery; version review; common/empty view and session labels.');
