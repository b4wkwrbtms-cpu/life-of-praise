import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import * as types from '../lib/types.ts';
import {applySongForm,sameSongForm,songFormPatch} from '../lib/song-form.ts';
const song={...types.newSong(),id:'song',title:'은혜',form:[{id:'v',type:'V1'},{id:'c',type:'C'}],pages:[{id:'page',width:800,height:1200,source:'original-pdf'}],exports:['old-export'],parts:{드럼:'브레이크'},key:'D'};
const patch=structuredClone(songFormPatch(song));patch.form.reverse();patch.pageLayouts[0].layout={...song.layout,x:.4,size:.07};
const next=applySongForm(song,patch);
assert.equal(sameSongForm(song,next),false);assert.equal(sameSongForm(song,{...song,notes:'unrelated',title:'private title'}),true);
assert.deepEqual(next.form.map(f=>f.id),['c','v'],'Existing section IDs, used by personal notes, survive reordering');
assert.deepEqual(next.pages.map(({layout,...p})=>p),song.pages);assert.equal(next.key,'D');assert.deepEqual(next.parts,song.parts);
assert.deepEqual(next.exports,[]);assert.equal(next.renderOnRead,true);assert.deepEqual(song.exports,['old-export'],'Original published snapshot is not mutated');
const require=createRequire(import.meta.url),module={exports:{}};
const code=ts.transpileModule(readFileSync('app/song-form-builder.tsx','utf8'),{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText;
new Function('require','module','exports',code)(id=>id==='@/lib/types'?types:require(id),module,module.exports);
const html=renderToStaticMarkup(React.createElement(module.exports.default,{song,onChange(){}}));
assert.ok(html.includes('Cx2')&&html.includes('Bridge x 2'));assert.ok(html.includes('1번 구간 앞으로')&&html.includes('2번 구간 삭제'));
assert.ok(!html.includes('type="file"')&&!html.includes('곡 제거')&&!html.includes('곡 제목'));
console.log('PASS: form patch preserves section IDs, page identity and leader-owned fields; builder renders repeated sections and accessible order controls without song/file management.');
